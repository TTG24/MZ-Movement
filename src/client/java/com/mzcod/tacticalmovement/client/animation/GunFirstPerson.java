	/**
	 * How a kind of gun is held: the grip's place in view (x right, y up, z ahead: negative) and how bent each elbow is.
	 * (Minecraft's first-person shoulders are about 0.66 ahead, 0.82 down and 0.5 out: the grips sit ahead of them, the
	 * guns' stocks reaching back towards the view.)
	 */
	private record Hold(float x, float y, float z, float gunElbow, float otherElbow) {
	}

	private static Hold hold(GunAnim.Style style) {
		Hold o = DBG_HOLD.get(style);
		return o != null ? o : baseHold(style);
	}

