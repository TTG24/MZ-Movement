	/** First person while drinking a perk: true when it drew the hand (the caller then skips vanilla's). */
	public static boolean renderDrink(PlayerRenderState playerState, ItemStack held, PoseStack poseStack, SubmitNodeCollector collector,
		int light, ArmDrawer arms) {
		Minecraft mc = Minecraft.getInstance();
		if (mc.player == null || playerState.avatarRenderState == null) {
			return false;
		}
		int id = mc.player.getId();
		float p = GunAnim.drink(id);
		if (p < 0) {
			bottle = ItemStack.EMPTY;
			lowered = 0;
			return false;
		}
		ItemStack off = mc.player.getOffhandItem();
		var model = off.get(net.minecraft.core.component.DataComponents.ITEM_MODEL);
		if (model != null && model.getNamespace().equals("mzguns") && model.getPath().startsWith("perk_")) {
			bottle = off.copy();
		}
		// the gun: lowered away and back
		lowered = p < 0.12F ? GunAnim.smooth(p / 0.12F) : p > 0.88F ? GunAnim.smooth((1 - p) / 0.12F) : 1;
		if (lowered < 0.98F && GunAnim.style(held) != null) {
			render(playerState, held, poseStack, collector, light, arms);
		}
		lowered = 0;
		if (p < DRINK_KEYS[0][0] || p > DRINK_KEYS[DRINK_KEYS.length - 1][0] || bottle.isEmpty()) {
			return true;
		}
		// the bottle along its path, with a dip at each gulp
		float[] k = new float[5];
		for (int i = 0; i + 1 < DRINK_KEYS.length; i++) {
			float[] a = DRINK_KEYS[i], b = DRINK_KEYS[i + 1];
			if (p <= b[0]) {
				float s = GunAnim.smooth((p - a[0]) / (b[0] - a[0]));
				for (int j = 0; j < 5; j++) {
					k[j] = Mth.lerp(s, a[j + 1], b[j + 1]);
				}
				break;
			}
		}
		for (float g : new float[] {0.44F, 0.54F, 0.63F}) {
			float d = (p - g) / 0.04F;
			if (d > 0 && d < 1) {
				k[1] -= 0.012F * Mth.sin(d * Mth.PI);
				k[3] += 6 * Mth.sin(d * Mth.PI);
			}
		}
		HumanoidArm mainArm = mc.player.getMainArm();
		int side = mainArm == HumanoidArm.RIGHT ? 1 : -1;
		Matrix4f entry = new Matrix4f(poseStack.last().pose());
		var renderer = mc.getEntityRenderDispatcher().getRenderer(playerState.avatarRenderState);
		PlayerModel pm = (PlayerModel) (Object) renderer.getModel();
		Vector3f at = new Vector3f(side * k[0], k[1], k[2]);
		org.joml.Quaternionf turn = new org.joml.Quaternionf().rotateX(k[3] * Mth.DEG_TO_RAD).rotateZ(-side * k[4] * Mth.DEG_TO_RAD);
		poseStack.pushPose();
		poseStack.translate(at.x, at.y, at.z);
		poseStack.mulPose(new Matrix4f().rotation(turn));
		mc.getItemModelResolver().updateForTopItem(BOTTLE_STATE, bottle,
			side > 0 ? ItemDisplayContext.THIRD_PERSON_RIGHT_HAND : ItemDisplayContext.THIRD_PERSON_LEFT_HAND, mc.level, mc.player, id);
		BOTTLE_STATE.submit(poseStack, collector, light, OverlayTexture.NO_OVERLAY, 0);
		poseStack.popPose();
		// the gun hand round the bottle, the arm running down and out of view
		Vector3f back = turn.transform(new Vector3f(side, 0, 0));
		GUN_ARM.attach(poseStack, arms, pm, playerState, mainArm, side, 0.45F, at, new Vector3f(side * 0.35F, -0.9F, 0.3F), back, entry);
		return true;
	}

