	private static Vector3f ads(GunAnim.Style style, String gunId) {
		Vector3f o = DBG_ADS.get(style);
		if (o != null) return o;
		// the grip low enough that the gun's top sits just under the crosshair; taller guns further out
		float sight = SIGHT.getOrDefault(gunId, 0.2F);
		float z = switch (style) {
			case PISTOL, REVOLVER -> -0.6F;
			case SMG -> -0.5F;
			case RIFLE, BOLT, PUMP, DOUBLE -> -0.48F;
			case LMG -> -0.52F;
		};
		return new Vector3f(0, -sight - 0.035F, z - 0.25F * Math.max(0, sight - 0.2F));
	}

	private static void updateAim(Minecraft mc, float reload, float sprint) {
		long now = System.nanoTime();
		float dt = aimNanos == 0 ? 0 : Math.min(0.1F, (now - aimNanos) / 1.0E9F);
		aimNanos = now;
		// sneak or the use button (right click), read off the keys themselves: the player's own sneaking flag is off while
		// tactically crouched or prone, where aiming has to work too
		int id = mc.player.getId();
		boolean key = mc.options.keyShift.isDown() || mc.options.keyUse.isDown();
		float want = key && reload < 0 && sprint < 0.3F && mc.gui.screen() == null && GunAnim.look(id) < 0 && GunAnim.drink(id) < 0 ? 1 : 0;
		// about a fifth of a second in or out
		aim += (want - aim) * (1 - (float) Math.exp(-dt * 14));
		if (Math.abs(want - aim) < 0.002F) aim = want;
	}

	private static void stopAim() {
		aim = 0;
		aimNanos = 0;
	}

