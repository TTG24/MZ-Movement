	private static int setHold(com.mojang.brigadier.context.CommandContext<net.fabricmc.fabric.api.client.command.v2.FabricClientCommandSource> c, boolean elbows) {
		if (lastStyle == null) {
			msg(c.getSource(), "hold a gun first");
			return 0;
		}
		Hold o = hold(lastStyle);
		Hold n = new Hold(f(c, "x"), f(c, "y"), f(c, "z"), elbows ? f(c, "gunElbow") : o.gunElbow, elbows ? f(c, "otherElbow") : o.otherElbow);
		DBG_HOLD.put(lastStyle, n);
		GUN_ARM.reset();
		OTHER_ARM.reset();
		msg(c.getSource(), lastStyle + " -> " + n);
		return 1;
	}

